<?php

namespace Sensiolabs\TypeScriptBundle\Types;

use Symfony\Component\AssetMapper\ImportMap\ImportMapEntry;
use Symfony\Component\AssetMapper\ImportMap\ImportMapType;
use Symfony\Component\Filesystem\Filesystem;
use Symfony\Component\HttpClient\HttpClient;
use Symfony\Contracts\HttpClient\HttpClientInterface;

/**
 * Downloads the TypeScript declaration files of the importmap packages from jsDelivr,
 * at the exact versions pinned in importmap.php, and generates a tsconfig file mapping
 * each import name to its declaration file.
 */
class TypeDefinitionsInstaller
{
    public const TSCONFIG_FILENAME = 'tsconfig.importmap.json';
    // Proves a node_modules directory was generated here, before it gets replaced
    private const MARKER_FILENAME = '.sensiolabs-typescript';

    private const FILE_URL = 'https://cdn.jsdelivr.net/npm/%s@%s/%s';
    private const FILE_LIST_URL = 'https://data.jsdelivr.com/v1/packages/npm/%s@%s?structure=flat';
    private const RESOLVE_VERSION_URL = 'https://data.jsdelivr.com/v1/packages/npm/%s/resolved?specifier=%s';

    private HttpClientInterface $httpClient;
    private Filesystem $filesystem;

    /**
     * Packages written to disk, keyed by name.
     *
     * @var array<string, array{version: string, manifests: array<string, array<string, mixed>>, files: array<string, true>}|null>
     */
    private array $packages = [];

    /**
     * Dependencies to install once every importmap package is, as name => version range.
     *
     * @var list<array{string, string}>
     */
    private array $pendingDependencies = [];

    // Built aside, so a failed run leaves the previous declaration files untouched
    private string $buildDir;

    public function __construct(
        private readonly string $typesDir,
        ?HttpClientInterface $httpClient = null,
    ) {
        $this->httpClient = $httpClient ?? HttpClient::create();
        $this->filesystem = new Filesystem();
    }

    /**
     * @param iterable<ImportMapEntry> $entries
     */
    public function install(iterable $entries): TypeDefinitionsReport
    {
        $targetDir = $this->typesDir.'/node_modules';
        if (is_dir($targetDir) && !is_file($targetDir.'/'.self::MARKER_FILENAME)) {
            throw new \RuntimeException(\sprintf('The "%s" directory was not generated by this bundle and will not be replaced: set "sensiolabs_typescript.types_dir" to a dedicated directory.', $targetDir));
        }

        $this->packages = [];
        $this->pendingDependencies = [];
        $this->buildDir = $targetDir.'.tmp';
        $this->filesystem->remove($this->buildDir);

        try {
            $imports = [];
            foreach ($entries as $entry) {
                if (!$entry->isRemotePackage() || ImportMapType::JS !== $entry->type) {
                    continue;
                }

                $imports[$entry->importName] = $this->installImport($entry->getPackageName(), $entry->version, '.'.$entry->getPackagePathString());
            }
            ksort($imports);

            // Installed last, so the versions pinned in the importmap win over the ranges dependencies ask for
            $this->installPendingDependencies();

            $this->filesystem->dumpFile($this->buildDir.'/'.self::MARKER_FILENAME, '');
            $this->filesystem->remove($targetDir);
            $this->filesystem->rename($this->buildDir, $targetDir);
            $this->writeTsConfig($imports);
        } finally {
            $this->filesystem->remove($this->buildDir);
        }

        return new TypeDefinitionsReport($imports, $this->typesDir.'/'.self::TSCONFIG_FILENAME);
    }

    /**
     * @return array{package: string, path: string}|null
     */
    private function installImport(string $packageName, string $version, string $subpath): ?array
    {
        if (null !== $import = $this->resolveInstalledEntry($packageName, $version, $subpath)) {
            return $import;
        }

        $typesPackageName = self::getDefinitelyTypedName($packageName);
        if (null === $typesVersion = $this->resolveDefinitelyTypedVersion($typesPackageName, $version)) {
            return null;
        }

        return $this->resolveInstalledEntry($typesPackageName, $typesVersion, $subpath);
    }

    /**
     * @return array{package: string, path: string}|null
     */
    private function resolveInstalledEntry(string $packageName, string $version, string $subpath): ?array
    {
        if (null === $package = $this->installPackage($packageName, $version)) {
            return null;
        }

        if (null === $entry = PackageTypesResolver::resolve($package['manifests'], $package['files'], $subpath)) {
            return null;
        }

        return ['package' => $packageName.'@'.$package['version'], 'path' => './node_modules/'.$packageName.'/'.$entry];
    }

    /**
     * Downloads the declaration files of a package, and queues its dependencies.
     * A package already written to disk is kept, whatever version is asked.
     *
     * @return array{version: string, manifests: array<string, array<string, mixed>>, files: array<string, true>}|null
     */
    private function installPackage(string $packageName, string $version): ?array
    {
        if (\array_key_exists($packageName, $this->packages)) {
            return $this->packages[$packageName];
        }
        $this->packages[$packageName] = null;

        $files = [];
        foreach ($this->fetchJson(\sprintf(self::FILE_LIST_URL, $packageName, $version))['files'] ?? [] as $file) {
            $name = ltrim($file['name'], '/');
            // File names come from a remote listing and end up as paths on disk
            if (str_contains($name, '..') || (!PackageTypesResolver::isDeclarationFile($name) && 'package.json' !== basename($name))) {
                continue;
            }
            $files[$name] = true;
        }

        if (!array_filter(array_keys($files), PackageTypesResolver::isDeclarationFile(...))) {
            return null;
        }

        $responses = [];
        foreach (array_keys($files) as $file) {
            $responses[$file] = $this->httpClient->request('GET', \sprintf(self::FILE_URL, $packageName, $version, $file));
        }
        $manifests = [];
        foreach ($responses as $file => $response) {
            $content = $response->getContent();
            $this->filesystem->dumpFile($this->buildDir.'/'.$packageName.'/'.$file, $content);
            if ('package.json' === basename($file)) {
                $decoded = json_decode($content, true, flags: 'package.json' === $file ? \JSON_THROW_ON_ERROR : 0);
                $manifests[$file] = \is_array($decoded) ? $decoded : [];
            }
        }
        $this->packages[$packageName] = ['version' => $version, 'manifests' => $manifests, 'files' => $files];

        // Declaration files may import their dependencies, which TypeScript resolves by walking up node_modules
        foreach ($manifests['package.json']['dependencies'] ?? [] as $dependency => $range) {
            $this->pendingDependencies[] = [$dependency, $range];
        }

        return $this->packages[$packageName];
    }

    private function installPendingDependencies(): void
    {
        while (null !== $pending = array_shift($this->pendingDependencies)) {
            [$dependency, $range] = $pending;
            if (\array_key_exists($dependency, $this->packages) || null === $dependencyVersion = $this->resolveVersion($dependency, $range)) {
                continue;
            }
            if (null === $this->installPackage($dependency, $dependencyVersion)) {
                $typesPackageName = self::getDefinitelyTypedName($dependency);
                if (null !== $typesVersion = $this->resolveDefinitelyTypedVersion($typesPackageName, $dependencyVersion)) {
                    $this->installPackage($typesPackageName, $typesVersion);
                }
            }
        }
    }

    /**
     * "lodash" => "@types/lodash", "@vendor/package" => "@types/vendor__package".
     */
    private static function getDefinitelyTypedName(string $packageName): string
    {
        return '@types/'.(str_starts_with($packageName, '@') ? str_replace('/', '__', substr($packageName, 1)) : $packageName);
    }

    /**
     * DefinitelyTyped versions follow the major.minor of the package they describe.
     */
    private function resolveDefinitelyTypedVersion(string $typesPackageName, string $version): ?string
    {
        if (!preg_match('/^(\d+)\.(\d+)/', $version, $matches)) {
            return null;
        }

        return $this->resolveVersion($typesPackageName, $matches[1].'.'.$matches[2])
            ?? $this->resolveVersion($typesPackageName, $matches[1]);
    }

    private function resolveVersion(string $packageName, string $range): ?string
    {
        $version = $this->fetchJson(\sprintf(self::RESOLVE_VERSION_URL, $packageName, urlencode($range)))['version'] ?? null;

        return \is_string($version) ? $version : null;
    }

    /**
     * @return array<string, mixed>
     */
    private function fetchJson(string $url): array
    {
        $response = $this->httpClient->request('GET', $url);

        if (404 === $response->getStatusCode()) {
            return [];
        }

        return $response->toArray();
    }

    /**
     * @param array<string, array{package: string, path: string}|null> $imports
     */
    private function writeTsConfig(array $imports): void
    {
        $paths = [];
        foreach ($imports as $importName => $import) {
            if (null !== $import) {
                $paths[$importName] = [$import['path']];
            }
        }

        $this->filesystem->dumpFile(
            $this->typesDir.'/'.self::TSCONFIG_FILENAME,
            json_encode(['compilerOptions' => ['paths' => (object) $paths]], \JSON_PRETTY_PRINT | \JSON_UNESCAPED_SLASHES | \JSON_THROW_ON_ERROR)."\n",
        );
    }
}
